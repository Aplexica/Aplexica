// Schema is the canonical description of every tunable parameter — the
// FR-10.9 deliverable ("Every parameter MUST have a JSON Schema entry
// describing its type, range, default value, unit, and human-readable
// description"). The shipped binary embeds Schema; `aplexica config
// schema` emits it as JSON; `aplexica config docs` renders it as
// Markdown.
//
// The schema is hand-authored alongside defaults.toml. Adding a new key
// is a two-step change: drop the default into defaults.toml AND add the
// matching Schema entry below. Validate() consults Schema to range-check
// every user-supplied value.
type SchemaEntry struct {
	Key             string   `json:"key"`
	Type            string   `json:"type"` // duration | int | int-or-all | float | bool | string | string-array
	Default         string   `json:"default"`
	Description     string   `json:"description"`
	Unit            string   `json:"unit,omitempty"`
	MinInt          *int64   `json:"min,omitempty"`
	MaxInt          *int64   `json:"max,omitempty"`
	MinFloat        *float64 `json:"min_float,omitempty"`
	MaxFloat        *float64 `json:"max_float,omitempty"`
	MinDuration     string   `json:"min_duration,omitempty"`
	MaxDuration     string   `json:"max_duration,omitempty"`
	ValidValues     []string `json:"valid_values,omitempty"`
	RestartRequired bool     `json:"restart_required,omitempty"`
	// AllowZero, when true, permits "0" / "0s" / "0.0" as a sentinel
	// meaning "feature disabled" even when MinInt/MinFloat/MinDuration
	// would otherwise reject zero (e.g. project_scan_interval = "0s"
	// disables the scan; retention.store_max_gb = 0 means unlimited).
	AllowZero bool `json:"allow_zero,omitempty"`
}

func intPtr(v int64) *int64       { return &v }
func floatPtr(v float64) *float64 { return &v }

