// schemaByKey is a lazy lookup map.
var schemaByKey = func() map[string]SchemaEntry {
	m := make(map[string]SchemaEntry, len(Schema))
	for _, e := range Schema {
		m[e.Key] = e
	}
	return m
}()

// knownSchemaSections returns the set of section names that appear in
// the schema. Used by applyEnv to disambiguate APLEXICA_<SECTION>_<FIELD>
// when field names contain underscores.
func knownSchemaSections() map[string]struct{} {
	out := map[string]struct{}{}
	for _, e := range Schema {
		if idx := strings.IndexByte(e.Key, '.'); idx > 0 {
			out[e.Key[:idx]] = struct{}{}
		}
	}
	return out
}

// SchemaJSON returns the schema as pretty-printed JSON. `aplexica config
// schema` writes this to stdout.
func SchemaJSON() ([]byte, error) {
	return json.MarshalIndent(Schema, "", "  ")
}

// SchemaMarkdown renders the schema as a human-readable Markdown table.
// `aplexica config docs` emits this.
func SchemaMarkdown() string {
	var b strings.Builder
	b.WriteString("# Aplexica configuration schema\n\n")
	b.WriteString("This document is generated from `internal/config/schema.go`. Every tunable parameter is listed here with its type, default, valid range, and units. Override precedence is shipped → system → user → project → env → CLI; see `aplexica config show` for the layer that set each effective value.\n\n")
	b.WriteString("| Key | Type | Default | Range | Unit | Restart? | Description |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	// Stable order matching Schema slice (already grouped by section).
	for _, e := range Schema {
		rng := markdownRange(e)
		restart := ""
		if e.RestartRequired {
			restart = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | `%s` | %s | %s | %s | %s |\n",
			e.Key, e.Type, e.Default, rng, e.Unit, restart, e.Description)
	}
	return b.String()
}

// markdownRange renders the human-readable range cell for one entry.
// Pulled out of SchemaMarkdown so the float / int-or-all additions are
// exercisable in isolation and the existing-key golden test stays
// byte-stable.
func markdownRange(e SchemaEntry) string {
	rng := ""
	switch {
	case e.MinInt != nil && e.MaxInt != nil:
		rng = fmt.Sprintf("[%d..%d]", *e.MinInt, *e.MaxInt)
	case e.MinInt != nil:
		rng = fmt.Sprintf("≥%d", *e.MinInt)
	case e.MaxInt != nil:
		rng = fmt.Sprintf("≤%d", *e.MaxInt)
	case e.MinFloat != nil && e.MaxFloat != nil:
		rng = fmt.Sprintf("[%s..%s]", trimFloat(*e.MinFloat), trimFloat(*e.MaxFloat))
	case e.MinFloat != nil:
		rng = "≥" + trimFloat(*e.MinFloat)
	case e.MaxFloat != nil:
		rng = "≤" + trimFloat(*e.MaxFloat)
	case e.MinDuration != "" && e.MaxDuration != "":
		rng = fmt.Sprintf("[%s..%s]", e.MinDuration, e.MaxDuration)
	case e.MinDuration != "":
		rng = "≥" + e.MinDuration
	case e.MaxDuration != "":
		rng = "≤" + e.MaxDuration
	case len(e.ValidValues) > 0:
		rng = strings.Join(e.ValidValues, " \\| ")
	}
	if e.AllowZero && rng != "" {
		rng += " (0 disables)"
	}
	return rng
}

// trimFloat renders a float64 range bound without trailing zeros so
// 0.0 → "0", 0.85 → "0.85", 1.0 → "1" (matches how the int bounds and
// the BRD's prose render the watermark fractions).
func trimFloat(f float64) string {
	return strconv.FormatFloat(f, 'f', -1, 64)
}

// SchemaValidate checks an Effective configuration against the Schema.
// Returns a sorted, deduplicated list of human-readable error strings —
// one per violation. The empty slice means "ok".
//
// Unknown keys (present in the Effective but absent from Schema) are
// reported as warnings, not failures, per BRD-10 §10.2: "Unknown keys
// (typos, deprecated keys from old versions) produce warnings at
// startup, not failures." Warnings are returned in the second slice.
func SchemaValidate(eff *Effective) (errs []string, warns []string) {
	for k, v := range eff.Values {
		entry, ok := schemaByKey[k]
		if !ok {
			warns = append(warns, fmt.Sprintf("unknown key %q (typo, or deprecated since this binary's schema)", k))
			continue
		}
		if msg := checkEntry(entry, v); msg != "" {
			errs = append(errs, fmt.Sprintf("%s: %s", k, msg))
		}
	}
	sort.Strings(errs)
	sort.Strings(warns)
	return errs, warns
}

func checkEntry(e SchemaEntry, v string) string {
	switch e.Type {
	case "int":
		n, err := strconv.ParseInt(v, 10, 64)
		if err != nil {
			return fmt.Sprintf("expected int, got %q", v)
		}
		if e.MinInt != nil && n < *e.MinInt {
			return fmt.Sprintf("value %d is below minimum %d", n, *e.MinInt)
		}
		if e.MaxInt != nil && n > *e.MaxInt {
			return fmt.Sprintf("value %d is above maximum %d", n, *e.MaxInt)
		}
	case "int-or-all":
		// The literal "all" is the keep-everything sentinel
		// (retention.keep_last_n_snapshots). Otherwise an int honoring the
		// entry's MinInt/MaxInt; when MinInt is unset the implicit floor is 0.
		if v == "all" {
			return ""
		}
		n, err := strconv.ParseInt(v, 10, 64)
		if err != nil {
			return fmt.Sprintf("expected int or 'all', got %q", v)
		}
		floor := int64(0)
		if e.MinInt != nil {
			floor = *e.MinInt
		}
		if n < floor {
			return fmt.Sprintf("value %d is below minimum %d", n, floor)
		}
		if e.MaxInt != nil && n > *e.MaxInt {
			return fmt.Sprintf("value %d is above maximum %d", n, *e.MaxInt)
		}
	case "float":
		// "0" / "0.0" is a permitted disable-sentinel when AllowZero is
		// set, even outside the [min..max] range (mirrors the int case).
		f, err := strconv.ParseFloat(v, 64)
		if err != nil {
			return fmt.Sprintf("expected float, got %q", v)
		}
		if e.AllowZero && f == 0 {
			return ""
		}
		if e.MinFloat != nil && f < *e.MinFloat {
			return fmt.Sprintf("value %s is below minimum %s", v, trimFloat(*e.MinFloat))
		}
		if e.MaxFloat != nil && f > *e.MaxFloat {
			return fmt.Sprintf("value %s is above maximum %s", v, trimFloat(*e.MaxFloat))
		}
	case "duration":
		// "0s" is a permitted disable-sentinel when AllowZero is set,
		// even outside the [min..max] range.
		if e.AllowZero && (v == "0" || v == "0s") {
			return ""
		}
		d, err := time.ParseDuration(durationCanonical(v))
		if err != nil {
			return fmt.Sprintf("expected duration (e.g. '60m'), got %q: %v", v, err)
		}
		if e.MinDuration != "" {
			min, err := time.ParseDuration(durationCanonical(e.MinDuration))
			if err == nil && d < min {
				return fmt.Sprintf("value %s is below minimum %s", v, e.MinDuration)
			}
		}
		if e.MaxDuration != "" {
			max, err := time.ParseDuration(durationCanonical(e.MaxDuration))
			if err == nil && d > max {
				return fmt.Sprintf("value %s is above maximum %s", v, e.MaxDuration)
			}
		}
	case "bool":
		if v != "true" && v != "false" {
			return fmt.Sprintf("expected bool 'true' or 'false', got %q", v)
		}
	case "string":
		if len(e.ValidValues) > 0 {
			for _, vv := range e.ValidValues {
				if v == vv {
					return ""
				}
			}
			return fmt.Sprintf("value %q is not one of %v", v, e.ValidValues)
		}
	case "string-array":
		// We accept the rendered "[a, b]" or unbracketed forms; deep
		// validation would require knowing element semantics. v0.70.0
		// only checks the rendering shape.
		// (No-op.)
	default:
		return fmt.Sprintf("schema: unknown type %q (programming error)", e.Type)
	}
	return ""
}

// durationCanonical maps user-friendly extended units ("7d", "30d") to
// time.ParseDuration-acceptable shapes (Go's stdlib doesn't recognize
// "d"). Everything else is passed through verbatim.
func durationCanonical(s string) string {
	if strings.HasSuffix(s, "d") {
		n := strings.TrimSuffix(s, "d")
		if v, err := strconv.Atoi(n); err == nil {
			return fmt.Sprintf("%dh", v*24)
		}
	}
	return s
}

// ParseDuration parses a config duration value, honoring the extended
// "d" (days) suffix that defaults.toml uses ("7d", "30d", "365d") and
// that Go's time.ParseDuration does not recognize. Exported so other
// packages (e.g. internal/retention) can read duration-typed config
// values consistently with how SchemaValidate range-checks them.
func ParseDuration(s string) (time.Duration, error) {
	return time.ParseDuration(durationCanonical(s))
}
