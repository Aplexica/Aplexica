// TestCheckEntry_IntOrAll_HonorsMinInt covers FR-03.25's floor: when an
// int-or-all entry sets MinInt (keep_last_n_snapshots uses MinInt=2), the
// numeric branch must reject values below it while the "all" sentinel still
// passes. A bare entry with no MinInt keeps the floor-0 behavior (the other
// int-or-all tests above).
func TestCheckEntry_IntOrAll_HonorsMinInt(t *testing.T) {
	e := SchemaEntry{Key: "x.n", Type: "int-or-all", MinInt: intPtr(2)}
	require.Equal(t, "", checkEntry(e, "all"), `"all" sentinel bypasses MinInt`)
	require.Equal(t, "", checkEntry(e, "2"), "value at MinInt floor is accepted")
	require.Equal(t, "", checkEntry(e, "9"), "value above MinInt floor is accepted")
	require.NotEmpty(t, checkEntry(e, "1"), "value below MinInt floor must be rejected")
	require.NotEmpty(t, checkEntry(e, "0"), "zero below MinInt floor must be rejected")
}

// ─────────────────────────────────────────────────────────────────────
// Rendering: SchemaMarkdown/SchemaJSON must surface the new ranges.
// ─────────────────────────────────────────────────────────────────────

func TestSchemaMarkdown_RendersFloatRangeAndIntOrAll(t *testing.T) {
	// Drive the render functions directly against synthetic entries so
	// the assertion doesn't depend on PR2 keys existing yet. We render a
	// one-row table by temporarily checking the package render helpers
	// via a constructed slice through the public funcs is not possible
	// (Schema is package-global); instead assert the range helper output
	// through markdownRange.
	fe := SchemaEntry{Key: "x.f", Type: "float", MinFloat: floatPtr(0), MaxFloat: floatPtr(1)}
	require.Equal(t, "[0..1]", markdownRange(fe))

	fz := SchemaEntry{Key: "x.f", Type: "float", MinFloat: floatPtr(1), MaxFloat: floatPtr(100), AllowZero: true}
	require.True(t, strings.Contains(markdownRange(fz), "(0 disables)"))
}
