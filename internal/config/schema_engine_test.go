// ─────────────────────────────────────────────────────────────────────
// "float" type: range check honoring AllowZero (0 disables the range,
// like the int case).
// ─────────────────────────────────────────────────────────────────────

func TestCheckEntry_Float_AcceptsInRange(t *testing.T) {
	e := SchemaEntry{
		Key:      "x.f",
		Type:     "float",
		MinFloat: floatPtr(0),
		MaxFloat: floatPtr(1),
	}
	require.Equal(t, "", checkEntry(e, "0.85"))
	require.Equal(t, "", checkEntry(e, "0"))
	require.Equal(t, "", checkEntry(e, "1"))
}

func TestCheckEntry_Float_RejectsAboveMax(t *testing.T) {
	e := SchemaEntry{
		Key:      "x.f",
		Type:     "float",
		MinFloat: floatPtr(0),
		MaxFloat: floatPtr(1),
	}
	msg := checkEntry(e, "1.5")
	require.NotEmpty(t, msg)
	require.Contains(t, msg, "above maximum")
}

func TestCheckEntry_Float_RejectsBelowMin(t *testing.T) {
	e := SchemaEntry{
		Key:      "x.f",
		Type:     "float",
		MinFloat: floatPtr(0.5),
		MaxFloat: floatPtr(1),
	}
	msg := checkEntry(e, "0.1")
	require.NotEmpty(t, msg)
	require.Contains(t, msg, "below minimum")
}

func TestCheckEntry_Float_RejectsNonNumeric(t *testing.T) {
	e := SchemaEntry{Key: "x.f", Type: "float"}
	msg := checkEntry(e, "abc")
	require.NotEmpty(t, msg)
	require.Contains(t, msg, "expected float")
}

func TestCheckEntry_Float_AllowZeroBypassesRange(t *testing.T) {
	// store_max_gb shape: 0 = unlimited is accepted via AllowZero even
	// though Min would otherwise reject it.
	e := SchemaEntry{
		Key:       "x.f",
		Type:      "float",
		MinFloat:  floatPtr(1),
		MaxFloat:  floatPtr(100),
		AllowZero: true,
	}
	require.Equal(t, "", checkEntry(e, "0"),
		"AllowZero must accept the 0 sentinel outside [min..max]")
	require.Equal(t, "", checkEntry(e, "0.0"))
	// A genuinely out-of-range non-zero value still fails.
	require.NotEmpty(t, checkEntry(e, "0.5"))
}

